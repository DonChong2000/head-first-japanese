// Builds ch/pN-summary.html for each part from the 重點整理 (aside.bullet-points) of the chapters before it in CHAPTERS.
// Run after editing any chapter's bullet-points box: node tools/summary.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const chapters = [...readFileSync(join(root, 'book.js'), 'utf8').matchAll(/\['([\w-]+)', '([^']+)', (\d), [01]\]/g)]
  .map(m => ({ file: m[1], title: m[2], part: +m[3] }));
const PART = ['', '第一部分', '第二部分', '第三部分', '第四部分', '第五部分'];
const LEVEL = ['', 'N5', 'N4', 'N3', 'N2', 'N1'];
const LEDE = ['',
  '由平假名到あります，十章的重點都在這一頁，當作 N5 的 cheat sheet 吧。',
  '普通形、可能形、授受、條件、被動使役、敬語入門：N4 的文法都在這一頁。',
  '名詞修飾、推測、はず・わけ・べき、敬語，加上 N3 讀解和聽解的做題方法。',
  '書面句型、である體、擬聲擬態語、職場日語和長文速讀，N2 要用的工具都放在這裏。',
  '考模擬試之前最後一次 git diff：N1 文法、詞彙、社論和正常語速聽解的重點。',
];

for (let p = 1; p <= 5; p++) {
  const file = `p${p}-summary`;
  const at = chapters.findIndex(c => c.file === file);
  if (at < 0) throw new Error(`${file} is not in CHAPTERS`);
  const chs = chapters.slice(0, at).filter(c => c.part === p && /^\d/.test(c.file));
  const next = chapters[at + 1];
  const sections = chs.map(c => {
    const html = readFileSync(join(root, 'ch', c.file + '.html'), 'utf8');
    const h1 = html.match(/<h1>([\s\S]*?)<\/h1>/)[1];
    const ul = html.match(/<aside class="bullet-points">[\s\S]*?(<ul>[\s\S]*?<\/ul>)[\s\S]*?<\/aside>/)?.[1];
    if (!ul) throw new Error(`ch/${c.file}.html has no bullet-points list`);
    return `<h2><a href="${c.file}.html">第 ${+c.file.slice(0, 2)} 章 · ${h1}</a></h2>\n${ul}`;
  }).join('\n\n');
  const [a, b] = [chs[0], chs.at(-1)].map(c => +c.file.slice(0, 2));
  writeFileSync(join(root, 'ch', file + '.html'), `<!doctype html>
<html lang="zh-Hant">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${LEVEL[p]} 總結 · 深入淺出日語</title>
<link rel="stylesheet" href="../style.css">
<link rel="manifest" href="../manifest.webmanifest">
<link rel="apple-touch-icon" href="../assets/apple-touch-icon.png">
<meta name="theme-color" content="#fcfcf9">
</head>
<body>
<main>
<!-- generated by tools/summary.mjs from each chapter's 重點整理; edit the chapters, then rerun it -->
<p class="chapter-no">${PART[p]} 總結</p>
<h1>${LEVEL[p]} 總結：第 ${a} 至 ${b} 章重點</h1>
<p class="lede">${LEDE[p]}</p>

<p>這一頁收集了第 ${a} 至 ${b} 章結尾的「重點整理」。按標題可以回到那一章。哪一條看來陌生，就回去重讀那一節，然後才做<a href="${next.file}.html">${next.title}</a>。</p>

${sections}
</main>
<script src="../book.js"></script>
</body>
</html>
`);
  console.log(`ch/${file}.html: chapters ${a}–${b}`);
}
